import 'package:flutter/material.dart';
import 'package:get/get.dart';
import 'package:core/core.dart';

class LeaveRequestController extends GetxController {
  final LeaveRepository _leaveRepository = Get.find<LeaveRepository>();
  final AuthService _authService = Get.find<AuthService>();

  final RxString selectedType = 'Casual'.obs;
  final Rx<DateTime?> startDate = Rx<DateTime?>(null);
  final Rx<DateTime?> endDate = Rx<DateTime?>(null);
  final TextEditingController reasonController = TextEditingController();

  final RxBool isLoading = false.obs;
  
  final List<String> leaveTypes = ['Casual', 'Sick', 'Annual', 'Other'];

  void selectDateRange(BuildContext context) async {
    final picked = await showDateRangePicker(
      context: context,
      firstDate: DateTime.now(),
      lastDate: DateTime.now().add(const Duration(days: 365)),
      builder: (context, child) {
        return Theme(
          data: ThemeData.dark().copyWith(
            colorScheme: const ColorScheme.dark(
              primary: AppColors.adminAccentStart,
              onPrimary: Colors.black,
              surface: AppColors.adminSurface,
              onSurface: Colors.white,
            ),
          ),
          child: child!,
        );
      },
    );
    if (picked != null) {
      startDate.value = picked.start;
      endDate.value = picked.end;
    }
  }

  Future<void> submitRequest() async {
    if (startDate.value == null || endDate.value == null) {
      Get.snackbar('Error', 'Please select a date range');
      return;
    }
    if (reasonController.text.trim().isEmpty) {
      Get.snackbar('Error', 'Please provide a reason');
      return;
    }

    isLoading.value = true;
    try {
      final user = await _authService.getFreshUserRecord();
      if (user == null) throw Exception('Not logged in');

      final request = LeaveRequest(
        id: '', // Will be generated by Firebase
        mrId: user.uid,
        leaveType: selectedType.value,
        startDate: startDate.value!,
        endDate: endDate.value!,
        reason: reasonController.text.trim(),
        status: 'pending',
        requestedAt: DateTime.now(),
      );

      await _leaveRepository.submitLeave(request);
      Get.snackbar('Success', 'Leave request submitted successfully');
      Get.back();
    } catch (e) {
      Get.snackbar('Error', 'Failed to submit leave request: $e');
    } finally {
      isLoading.value = false;
    }
  }
}
